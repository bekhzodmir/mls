function consent(
  clientId: ID,
  purpose: Consent["purpose"],
  channel: Consent["channel"],
  grantedAt: string,
  revokedAt?: string,
): Consent {
  const item: Consent = {
    id: `cons-${clientId}-${purpose}`,
    purpose,
    channel,
    grantedAt,
    textVersion: "client-consent-v1.2-demo",
  };
  if (revokedAt) item.revokedAt = revokedAt;
  return item;
}

