/** Complete, explicit split terms (§35.6): never a bare "70/30". */
export function split(
  preset: SplitPreset,
  listingSidePercent: number,
  currency: Currency,
  extra: Partial<Omit<CommissionTerms, "preset" | "listingSidePercent" | "buyerSidePercent" | "currency">> = {},
): CommissionTerms {
  return {
    preset,
    listingSidePercent,
    buyerSidePercent: 100 - listingSidePercent,
    basis: "gross_commission",
    currency,
    payoutCondition: "on_deal_closing",
    ...extra,
  };
}

function check(
  listingId: ID,
  subject: VerificationItem["subject"],
  status: VerificationItem["status"],
  method: VerificationItem["method"],
  source: string,
  checkedAt?: ISODateTime,
  note?: string,
): VerificationItem {
  const item: VerificationItem = { id: `ver-${listingId}-${subject}`, subject, status, method, source };
  if (checkedAt) item.checkedAt = checkedAt;
  if (note) item.note = note;
  return item;
}

function contractCheck(listingId: ID, number: string, checkedAt: ISODateTime): VerificationItem {
  return check(listingId, "contract", "confirmed", "document_review", `Договор оказания услуг № ${number}`, checkedAt);
}

function consentCheck(
  listingId: ID,
  method: "owner_statement" | "document_review",
  checkedAt: ISODateTime,
): VerificationItem {
  return check(
    listingId,
    "owner_consent",
    "confirmed",
    method,
    method === "owner_statement" ? "Звонок собственнику, запись в журнале" : "Письменное согласие собственника",
    checkedAt,
  );
}

function ownershipCheck(listingId: ID, checkedAt: ISODateTime): VerificationItem {
  return check(listingId, "ownership", "confirmed", "official_source", "Выписка из реестра прав (демо)", checkedAt);
}

interface ListingSpec {
  id: ID;
  propertyId: ID;
  agentId: ID;
  organizationId?: ID;
  dealType: DealType;
  currency: Currency;
  /** Price steps, oldest first: [when, major amount]. The last one is the current price. */
  prices: [ISODateTime, number][];
  status: ListingStatus;
  confidentiality: Confidentiality;
  source: SourceKind;
  exclusive?: boolean;
  cooperation?: CommissionTerms;
  /** Service contract number (a document reference, not a seeded entity). */
  contract?: { number: string; expiresAt: ISODateTime };
  verifications: VerificationItem[];
  description: string;
  photoCount: number;
  publishedAt: ISODateTime;
  lastConfirmedAt?: ISODateTime;
  expiresAt?: ISODateTime;
  updatedAt?: ISODateTime;
}

function latest(...values: (ISODateTime | undefined)[]): ISODateTime {
  return values
    .filter((value): value is ISODateTime => Boolean(value))
    .sort()
    .reverse()[0];
}

function listing(spec: ListingSpec): Listing {
  const priceHistory: PriceChange[] = spec.prices.map(([at, amount]) => ({
    price: money(amount, spec.currency),
    at,
    byAgentId: spec.agentId,
  }));
  const current = priceHistory[priceHistory.length - 1];
  const result: Listing = {
    id: spec.id,
    propertyId: spec.propertyId,
    agentId: spec.agentId,
    dealType: spec.dealType,
    price: { ...current.price },
    priceHistory,
    status: spec.status,
    confidentiality: spec.confidentiality,
    source: spec.source,
    exclusive: spec.exclusive ?? false,
    verifications: spec.verifications,
    description: spec.description,
    photoCount: spec.photoCount,
    publishedAt: spec.publishedAt,
    updatedAt: spec.updatedAt ?? latest(spec.publishedAt, spec.lastConfirmedAt, current.at),
  };
  if (spec.organizationId) result.organizationId = spec.organizationId;
  if (spec.cooperation) result.cooperation = spec.cooperation;
  if (spec.contract) {
    result.contractId = spec.contract.number;
    result.contractExpiresAt = spec.contract.expiresAt;
  }
  if (spec.lastConfirmedAt) result.lastConfirmedAt = spec.lastConfirmedAt;
  if (spec.expiresAt) result.expiresAt = spec.expiresAt;
  return result;
}

